const lessonNumber = (title = '') => Number(/^Bài\s+(\d+)/.exec(title)?.[1])

export const getLessonModel = (lesson) => KNTT_LESSON_MODELS[`${Number(lesson?.grade_level)}-${lessonNumber(lesson?.title)}`] || null

export const lessonModelSimulation = (lesson, base) => {
  const model = getLessonModel(lesson)
  if (!model) return null
  const layers = model.stages.map(([name, , note], index) => ({ id: `stage${index + 1}`, name, note }))
  return {
    ...base,
    modelId: 'lesson',
    lessonModel: model,
    label: `Bài ${lessonNumber(lesson.title)}`,
    title: lesson.title.replace(/^Bài\s+\d+\.\s*/, ''),
    subtitle: lesson.description || base.subtitle,
    objective: model.objective,
    layers,
    checkpoints: lesson.key_points?.length ? lesson.key_points : base.checkpoints,
  }
}
